package com.example.hokkaidoec.entity;

public class Region {
	private int id;
	private String regionName;

	public Region() {

	}

	public int getId() {
		return id;
	}

	public void setId(int id) {
		this.id = id;
	}

	public String getRegionName() {
		return regionName;
	}

	public void setRegionName(String regionName) {
		this.regionName = regionName;
	}
}
